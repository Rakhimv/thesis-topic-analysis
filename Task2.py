def get_category(title):
    title_lower = title.lower()
    for category, keywords in categories.items():
        if any(kw in title_lower for kw in keywords):
            return category
    return "Прочее"

data["category"] = data["Title_ru"].apply(get_category)

yearly_categories = data.groupby(["Graduation", "category"]).size().unstack(fill_value=0)

fig, ax = plt.subplots(figsize=(14, 8))
yearly_categories.plot(kind='bar', stacked=True, ax=ax, colormap='tab20')

ax.set_xlabel('Год выпуска', fontsize=12)
ax.set_ylabel('Количество работ', fontsize=12)
ax.set_title('Распределение тематик дипломных работ по годам', fontsize=14)
plt.show()